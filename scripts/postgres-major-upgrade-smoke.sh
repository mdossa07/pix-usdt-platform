#!/usr/bin/env bash
set -Eeuo pipefail

# Disposable logical-upgrade rehearsal. It never mounts or modifies the
# project's existing pixsplit_pg volume.
command -v docker >/dev/null 2>&1 || {
  echo "docker CLI is required" >&2
  exit 1
}
docker info >/dev/null 2>&1 || {
  echo "Docker daemon is not reachable" >&2
  exit 1
}

suffix="${GITHUB_RUN_ID:-local}-$$"
network="pixsplit-pg-upgrade-${suffix}"
source_name="pixsplit-pg16-source-${suffix}"
target_name="pixsplit-pg18-target-${suffix}"
target_volume="pixsplit-pg18-smoke-${suffix}"
db_user="pixsplit_migration"
db_password="$(openssl rand -hex 24)"
db_name="pixsplit_upgrade_rehearsal"
dump_path="/tmp/pixsplit-pg-upgrade-${suffix}.dump"

cleanup() {
  set +e
  docker rm -f -v "$source_name" "$target_name" >/dev/null 2>&1
  docker volume rm "$target_volume" >/dev/null 2>&1
  docker network rm "$network" >/dev/null 2>&1
}
trap cleanup EXIT

wait_for_postgres() {
  local container="$1"
  local attempt
  for attempt in $(seq 1 60); do
    if docker exec "$container" pg_isready -U "$db_user" -d postgres >/dev/null 2>&1; then
      return 0
    fi
    sleep 2
  done
  docker logs "$container" >&2
  echo "PostgreSQL did not become ready: $container" >&2
  return 1
}

docker network create "$network" >/dev/null
docker volume create "$target_volume" >/dev/null

# Source: a disposable PostgreSQL 16 cluster, isolated from all project volumes.
docker run -d \
  --name "$source_name" \
  --network "$network" \
  --network-alias pg16-source \
  -e POSTGRES_USER="$db_user" \
  -e POSTGRES_PASSWORD="$db_password" \
  -e POSTGRES_DB=postgres \
  --tmpfs /var/lib/postgresql/data:rw,nosuid,nodev,size=1g \
  postgres:16-alpine >/dev/null

# Target: PostgreSQL 18 with the new official-image parent mount layout.
# The temporary named volume is deleted by the EXIT trap.
docker run -d \
  --name "$target_name" \
  --network "$network" \
  -e POSTGRES_USER="$db_user" \
  -e POSTGRES_PASSWORD="$db_password" \
  -e POSTGRES_DB=postgres \
  -v "$target_volume:/var/lib/postgresql" \
  postgres:18-alpine >/dev/null

wait_for_postgres "$source_name"
wait_for_postgres "$target_name"

# Build a representative source schema with identity sequences, relational
# constraints, an index, JSONB and exact numeric precision.
docker exec "$source_name" psql -U "$db_user" -d postgres -v ON_ERROR_STOP=1 \
  -c "CREATE DATABASE $db_name" >/dev/null
docker exec "$source_name" psql -U "$db_user" -d "$db_name" -v ON_ERROR_STOP=1 \
  -c "CREATE TABLE migration_probe (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        marker text NOT NULL,
        payload jsonb NOT NULL,
        amount_usdt numeric(28,8) NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        CONSTRAINT migration_probe_marker_unique UNIQUE (marker),
        CONSTRAINT migration_probe_amount_usdt_nonnegative CHECK (amount_usdt >= 0)
      )" \
  -c "CREATE TABLE migration_probe_child (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_id bigint NOT NULL REFERENCES migration_probe(id),
        detail text NOT NULL
      )" \
  -c "CREATE INDEX migration_probe_created_at_idx ON migration_probe(created_at)" >/dev/null

# This database is created from a clean disposable cluster, so the first
# generated identity is 1 and the second is 2. The child fixture references 1.
# The target-side insert below must then return 3 after the logical restore.
docker exec "$source_name" psql -U "$db_user" -d "$db_name" -v ON_ERROR_STOP=1 \
  -c "INSERT INTO migration_probe (marker, payload, amount_usdt, created_at)
      VALUES ('preserved-through-major-upgrade', '{\"source\":16,\"target\":18}', 123456789.12345678, '2026-11-25T00:00:00Z')" \
  -c "INSERT INTO migration_probe (marker, payload, amount_usdt, created_at)
      VALUES ('sequence-advance', '{\"source\":16,\"sequence\":2}', 0.00000001, '2026-11-25T00:01:00Z')" \
  -c "INSERT INTO migration_probe_child (parent_id, detail)
      VALUES (1, 'foreign-key-preserved')" >/dev/null

# Use PostgreSQL 18's pg_dump client against the PostgreSQL 16 source.
docker exec -e PGPASSWORD="$db_password" "$target_name" \
  pg_dump -h pg16-source -U "$db_user" -d "$db_name" \
  --format=custom --file="$dump_path"

# Create an empty target database and restore the custom-format dump.
docker exec "$target_name" psql -U "$db_user" -d postgres -v ON_ERROR_STOP=1 \
  -c "CREATE DATABASE $db_name" >/dev/null
docker exec "$target_name" pg_restore \
  --exit-on-error --no-owner --no-privileges \
  -U "$db_user" -d "$db_name" "$dump_path"

actual_marker="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT marker FROM migration_probe WHERE marker = 'preserved-through-major-upgrade'")"
if [[ "$actual_marker" != "preserved-through-major-upgrade" ]]; then
  echo "PostgreSQL 16→18 text marker verification failed" >&2
  exit 1
fi

json_payload="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT payload->>'target' FROM migration_probe WHERE marker = 'preserved-through-major-upgrade'")"
if [[ "$json_payload" != "18" ]]; then
  echo "PostgreSQL 18 JSONB verification failed" >&2
  exit 1
fi

numeric_amount="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT amount_usdt::text FROM migration_probe WHERE marker = 'preserved-through-major-upgrade'")"
if [[ "$numeric_amount" != "123456789.12345678" ]]; then
  echo "PostgreSQL 18 numeric precision verification failed: $numeric_amount" >&2
  exit 1
fi

child_count="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT count(*) FROM migration_probe_child child
      JOIN migration_probe parent ON parent.id = child.parent_id
      WHERE parent.marker = 'preserved-through-major-upgrade'
        AND child.detail = 'foreign-key-preserved'")"
if [[ "$child_count" != "1" ]]; then
  echo "PostgreSQL 18 foreign-key/data verification failed: $child_count" >&2
  exit 1
fi

constraint_count="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT count(*) FROM pg_constraint
      WHERE conrelid = 'public.migration_probe'::regclass
        AND convalidated
        AND conname IN ('migration_probe_pkey', 'migration_probe_marker_unique', 'migration_probe_amount_usdt_nonnegative')")"
if [[ "$constraint_count" != "3" ]]; then
  echo "PostgreSQL 18 primary/unique/check constraint verification failed: $constraint_count" >&2
  exit 1
fi

foreign_key_count="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT count(*) FROM pg_constraint
      WHERE conrelid = 'public.migration_probe_child'::regclass
        AND contype = 'f'
        AND convalidated")"
if [[ "$foreign_key_count" != "1" ]]; then
  echo "PostgreSQL 18 foreign-key constraint verification failed: $foreign_key_count" >&2
  exit 1
fi

index_present="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "SELECT to_regclass('public.migration_probe_created_at_idx') IS NOT NULL")"
if [[ "$index_present" != "t" ]]; then
  echo "PostgreSQL 18 index verification failed" >&2
  exit 1
fi

# An insert without an explicit ID proves that pg_dump/pg_restore preserved
# the identity sequence state, not just the table rows.
next_identity="$(docker exec "$target_name" psql -U "$db_user" -d "$db_name" -At -v ON_ERROR_STOP=1 \
  -c "INSERT INTO migration_probe (marker, payload, amount_usdt)
      VALUES ('sequence-after-restore', '{}', 0)
      RETURNING id")"
if [[ "$next_identity" != "3" ]]; then
  echo "PostgreSQL 18 identity sequence verification failed: expected 3, got $next_identity" >&2
  exit 1
fi

echo "PostgreSQL 16→18 logical dump/restore rehearsal passed."
echo "Verified: PK/identity, sequence state, FK, unique/check constraints, index, JSONB and numeric precision."
echo "Source and target were disposable containers; no project volume was mounted."
